#!/usr/bin/env bash
# Turn a bootstrapped box (run bootstrap-node.sh first) into the control node.
#
# Usage (as your normal user, NOT with sudo — it asks for sudo when needed):
#   bash setup-control-node.sh
#
# What it does:
#   - logs in to GitHub (gh) and clones UpperLab to ~/UpperLab
#   - creates an SSH key and copies it to every box in inventory/hosts
#   - writes ~/.ssh/config so `ssh bpc-2000` etc. just works
#   - installs Claude Code and runs `claude remote-control` as a service,
#     so this box is always reachable from the Claude app
set -euo pipefail

REPO="Mitchnboof/UpperLab"
REPO_DIR="$HOME/UpperLab"

if [[ $EUID -eq 0 ]]; then
  echo "Run as your normal user, not root/sudo." >&2
  exit 1
fi

echo "==> GitHub CLI"
command -v gh >/dev/null || sudo apt-get install -yq gh
if ! gh auth status >/dev/null 2>&1; then
  echo "Log in to GitHub: choose GitHub.com, HTTPS, and 'Login with a web browser'."
  echo "It shows a code; open https://github.com/login/device on your phone/PC and enter it."
  gh auth login --hostname github.com --git-protocol https --web
fi
gh auth setup-git

echo "==> Clone UpperLab"
if [[ -d "$REPO_DIR/.git" ]]; then
  git -C "$REPO_DIR" pull --ff-only
else
  gh repo clone "$REPO" "$REPO_DIR"
fi

echo "==> SSH key"
[[ -f "$HOME/.ssh/id_ed25519" ]] || ssh-keygen -t ed25519 -N "" -C "control@$(hostname)" -f "$HOME/.ssh/id_ed25519"

echo "==> SSH config from inventory/hosts"
SSH_CFG="$HOME/.ssh/config"
touch "$SSH_CFG"; chmod 600 "$SSH_CFG"
sed -i '/# BEGIN UpperLab/,/# END UpperLab/d' "$SSH_CFG"
{
  echo "# BEGIN UpperLab (generated by setup-control-node.sh)"
  grep -Ev '^\s*(#|$)' "$REPO_DIR/inventory/hosts" | while read -r name ip user _; do
    printf 'Host %s\n  HostName %s\n  User %s\n\n' "$name" "$ip" "$user"
  done
  echo "# END UpperLab"
} >> "$SSH_CFG"

echo "==> Copy SSH key to each box (asks each box's password once)"
grep -Ev '^\s*(#|$)' "$REPO_DIR/inventory/hosts" | while read -r name _; do
  [[ "$name" == "$(hostname)" ]] && continue
  if ssh -n -o BatchMode=yes -o ConnectTimeout=5 "$name" true 2>/dev/null; then
    echo "   $name: key already works"
  else
    ssh-copy-id -o ConnectTimeout=5 "$name" </dev/tty || echo "   $name: skipped (unreachable or wrong password)"
  fi
done

echo "==> Claude Code"
export PATH="$HOME/.local/bin:$PATH"
command -v claude >/dev/null || curl -fsSL https://claude.ai/install.sh | bash
read -rp "Is Claude already signed in on this box? [y/N] " signed_in </dev/tty
if [[ ! "$signed_in" =~ ^[Yy] ]]; then
  echo "Claude will open: sign in with your account, then type /exit to come back here."
  (cd "$REPO_DIR" && claude) </dev/tty
fi

echo "==> claude remote-control as an always-on service"
mkdir -p "$HOME/.config/systemd/user"
cat > "$HOME/.config/systemd/user/claude-remote.service" <<EOF
[Unit]
Description=Claude remote-control in UpperLab
After=network-online.target

[Service]
WorkingDirectory=$REPO_DIR
Environment=PATH=$HOME/.local/bin:/usr/local/bin:/usr/bin:/bin
ExecStart=$HOME/.local/bin/claude remote-control
Restart=always
RestartSec=30

[Install]
WantedBy=default.target
EOF
# Linger = user services start at boot without anyone logging in
sudo loginctl enable-linger "$USER"
systemctl --user daemon-reload
systemctl --user enable --now claude-remote.service

echo
echo "Done. Check the service with:  systemctl --user status claude-remote"
echo "Its session should now be listed in the Claude app."
echo "Test SSH:  ssh bpc-2000 hostname"
